function currentLang(): string {
  if (typeof window === "undefined") return "en";
  try {
    return window.localStorage.getItem("language") ?? "en";
  } catch {
    return "en";
  }
}

// Simplified Chinese also serves zh-TW until a traditional dict exists.
const DICT: Record<string, string> | null = currentLang().startsWith("zh") ? ZH : null;

export function t(key: string): string {
  return DICT?.[key] ?? key;
}

/** A registry string that carries both languages (palette and look names). */
export function tl(text: { en: string; zh: string }): string {
  return DICT ? text.zh : text.en;
}

/** A count: `one` when n is 1 (a key with the digit written out, "1 block selected"),
 *  otherwise `many` with {n} replaced ("{n} blocks selected"). */
export function tn(one: string, many: string, n: number): string {
  return t(n === 1 ? one : many).replace("{n}", String(n));
}
